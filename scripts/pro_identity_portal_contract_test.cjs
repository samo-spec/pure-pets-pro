const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const swift = fs.readFileSync(path.join(root, 'PurePetsPro/AdminCore/Auth/PPProLoginSurfaceController.swift'), 'utf8');
const gate = swift.slice(swift.indexOf('private struct PPProIdentityGateView:'), swift.indexOf('// MARK: - PULSE COMMAND CENTER'));
assert(gate.includes('accessibilityIdentifier("pro.login.screen")'));
for (const id of ['phone','country','continue','apple','google','support','language','providerApplication']) assert(gate.includes('pro.login.'+id), 'Missing accessible login control: '+id);
assert(!gate.includes('repeatForever'), 'No decorative infinite motion on the login route');
assert(gate.includes('model.isBusy'), 'Busy state remains authoritative');
assert(gate.includes('onPhoneContinue') && gate.includes('onApple') && gate.includes('onGoogle'));
assert(gate.includes('onProviderApplication') && gate.includes('onSupport') && gate.includes('onLanguage'));
assert(gate.includes('PPCountryPickerView') && gate.includes('PPPhoneNumberTextField'));
assert(gate.includes('layoutDirection') && gate.includes('sizeCategory'));
assert(gate.includes('.foregroundStyle(disabled ? palette.secondary : Color.white)'), 'Primary action needs contrast on the brand pink background');
assert(gate.includes('pro.login.country.search') || swift.includes('pro.login.country.search'), 'Country search must be addressable');
const service = fs.readFileSync(path.join(root, 'PurePetsPro/ServiceSection/PPProviderServicesReinventionView.swift'),'utf8');
assert(!service.includes('PPServiceManager.sharedManager()'), 'Swift imported singleton name must match SDK');
console.log('PASS native login source contracts and compile regression guard');
